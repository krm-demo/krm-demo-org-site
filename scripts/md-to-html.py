#!/usr/bin/env python3
"""Turns a Markdown article from docs/ into a page of the site.

    usage: scripts/md-to-html.py docs/<name>[.<lang>].md <output dir>/<name>[.<lang>].html

scripts/build.sh runs this for every docs/*.md, so the pages are never committed.

What the Markdown may contain, beyond the usual:
- Language: taken from the file name (chebyshev.ru.md -> "ru"); without a suffix the article is English.
  The other docs/<name>.<lang>.md files are its translations; each page gets a switcher for them.
- Sections: a heading that starts with a number ("## 3. Title", "### 1.4 Title") gets the id "s3" / "s1-4",
  the same in every language. Link to it from any article as [§1.4](chebyshev.en.md#s1-4); the ".md" becomes
  ".html" on the site, and on GitHub the same link opens the Markdown file.
- Math: $...$ (inline) and $$...$$ (display). Rendered here with KaTeX (through scripts/katex-render.js),
  so the page needs only KaTeX's stylesheet. A formula KaTeX cannot parse stops the build.
  If Node or KaTeX is not installed, the formulas are rendered in the browser instead.
- Code: fenced blocks with a language (```python) are highlighted with Pygments, if it is installed.
- Proofs and long listings: <details markdown="1"><summary>Proof</summary> ... </details>.
- Technologies: link the first mention of every library, tool or platform to its official page, and mark it
  with a class (attr_list syntax): [Jackson](https://github.com/FasterXML/jackson){: .tech} for libraries,
  platforms and products, [jq](https://jqlang.org/){: .cmd} for command-line tools. Links that leave the site
  open in a new tab.
- Figures: ![description](figures/name.svg) on its own line, followed by a caption paragraph. The SVG is drawn
  into the page so that it takes the colours of the current skin (see scripts/make-figures.py).

Needs Python 3 with the "markdown" package; see scripts/install-build-deps.sh.
"""
import glob
import html
import json
import os
import re
import subprocess
import sys

import markdown
from markdown.extensions.toc import slugify_unicode

import publish_dates

REPO_URL = "https://github.com/krm-demo/krm-demo-org-site"
HERE = os.path.dirname(os.path.abspath(__file__))

LANG_NAMES = {"en": "English", "ru": "Русский"}
UI = {
    "en": {"home": "Home", "source": "Markdown source", "section": "The Collection", "versions": "Read in",
           "contents": "Contents", "anchor": "Link to this section"},
    "ru": {"home": "Главная", "source": "Исходник в Markdown", "section": "Запасники", "versions": "Читать на",
           "contents": "Содержание", "anchor": "Ссылка на этот раздел"},
}
REFERENCE_HEADINGS = {"references", "литература", "источники"}

TEMPLATE = """<!DOCTYPE html>
<html lang="{lang}">
<head>
    <title>{title} — krm-demo</title>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="{description}">
{alternates}{math_head}    <!-- Site icon [(-)]: site.js swaps these for the current skin (drawn by scripts/make-favicons.py). -->
    <link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-light-32x32.png">
    <link rel="icon" type="image/png" sizes="16x16" href="icons/favicon-light-16x16.png">
    <link rel="apple-touch-icon" sizes="180x180" href="icons/apple-touch-icon-light-180x180.png">
    <link rel="manifest" href="manifest.json">
    <meta name="theme-color" content="#123a73">
    <link href="site.css" rel="stylesheet">
    <script src="site.js"></script>
</head>
<body>
<!-- Generated by scripts/md-to-html.py from {source} — edit the Markdown, not this file. -->

<header class="site-head">
    <div class="wrap">
        <a class="brand" href="./" aria-label="krm-demo"><span class="wm-br" aria-hidden="true">[(</span><span class="wm-name" aria-hidden="true">krm-demo</span><span class="wm-br" aria-hidden="true">)]</span></a>
        <a class="brand-section" href="./#collection">{section}</a>
        <div id="lang-switch"></div>
        <div id="skin-switch"></div>
    </div>
</header>

<main class="wrap article-layout{layout_class}">
    <article>
        <p class="article-nav">
            <a href="./">&larr; {home}</a> · <a href="{repo}/blob/main/{source}" target="_blank" rel="noopener">{source_label}</a>
            {switcher}
            <span id="visit-badge"></span>
        </p>
{dates}{body}
    </article>
{toc}</main>

<footer class="site-foot">
    <div class="wrap"><span id="build-info">loading build info…</span></div>
</footer>
<script src="build-site-info.js"></script>
<script src="visit-badge.js"></script>

</body>
</html>
"""

# Math already rendered: only the stylesheet is needed (copied into dist/vendor/katex by scripts/build.sh).
MATH_HEAD_STATIC = '    <link rel="stylesheet" href="vendor/katex/katex.min.css">\n'
# Fallback when KaTeX is not installed where the site is built: render in the browser.
MATH_HEAD_BROWSER = """    <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.47/dist/katex.min.css">
    <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.47/dist/katex.min.js"></script>
    <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.47/dist/contrib/auto-render.min.js"
            onload="renderMathInElement(document.querySelector('main'), {delimiters: [
                {left: '$$', right: '$$', display: true}, {left: '$', right: '$', display: false}],
                throwOnError: false});"></script>
"""

# $$...$$ first (may span lines), then $...$ on one line.
MATH_RE = re.compile(r"\$\$.+?\$\$|(?<![\\$])\$(?![\s$])[^$\n]+?(?<!\s)\$", re.S)
CODE_RE = re.compile(r"```.*?```|`[^`\n]+`", re.S)


def split_name(path):
    """docs/chebyshev.ru.md -> ("chebyshev", "ru"); docs/page-refresh.md -> ("page-refresh", None)"""
    base = os.path.basename(path)[:-len(".md")]
    m = re.match(r"^(.*)\.([a-z]{2})$", base)
    return (m.group(1), m.group(2)) if m else (base, None)


def section_id(value, separator):
    """Heading text -> id: "1.4 Title" -> "s1-4", "3. Title" -> "s3", "References"/"Литература" -> "references"."""
    m = re.match(r"\s*(\d+(?:\.\d+)*)[.\s]", value)
    if m:
        return "s" + m.group(1).replace(".", "-")
    if value.strip().lower() in REFERENCE_HEADINGS:
        return "references"
    return slugify_unicode(value, separator)


def protect_math(text):
    """Swaps formulas for placeholders so that Markdown leaves them alone; returns (text, formulas)."""
    formulas, codes = [], []

    def keep(m):
        formulas.append(m.group(0))
        return f"MATHPLACEHOLDER{len(formulas) - 1}X"

    def keep_code(m):
        codes.append(m.group(0))
        return f"CODEPLACEHOLDER{len(codes) - 1}X"

    # code may contain "$" that is not math: hide code first, then the math, then bring the code back
    text = CODE_RE.sub(keep_code, text)
    text = MATH_RE.sub(keep, text)
    text = re.sub(r"CODEPLACEHOLDER(\d+)X", lambda m: codes[int(m.group(1))], text)
    return text, formulas


def render_math(formulas):
    """Formulas -> KaTeX HTML, or None when Node/KaTeX is not available (the browser renders them then)."""
    items = [{"tex": f[2:-2] if f.startswith("$$") else f[1:-1], "display": f.startswith("$$")} for f in formulas]
    try:
        run = subprocess.run(["node", os.path.join(HERE, "katex-render.js")], input=json.dumps(items),
                             capture_output=True, text=True, timeout=300)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    if run.returncode == 3:      # katex-render.js: the katex package is not installed
        return None
    if run.returncode != 0:
        sys.exit("md-to-html: KaTeX could not render a formula:\n" + run.stderr)
    return json.loads(run.stdout)


def toc_list(tokens):
    if not tokens:
        return ""
    items = "".join(f'<li><a href="#{t["id"]}">{t.get("html", t["name"])}</a>{toc_list(t["children"])}</li>'
                    for t in tokens)
    return f"<ol>{items}</ol>"


def dates_line(name, lang):
    """Small line under the navigation: when the article reached the preview and krm-demo.org (scripts/publish_dates.py)."""
    d = publish_dates.dates(name)
    if not d["preview"]:
        return ""
    ru = lang == "ru"
    stamp = lambda m: f'<time datetime="{m.isoformat()}">{publish_dates.day_time(m, lang)}</time>'
    parts = [f'{"Превью" if ru else "Preview"}: {stamp(d["preview"])}']
    if d["release"]:
        parts.append(f'{"на krm-demo.org" if ru else "krm-demo.org"}: {stamp(d["release"])} ({d["tag"]})')
    else:
        parts.append("на krm-demo.org: ещё нет" if ru else "krm-demo.org: not yet")
    return f'        <p class="article-dates">{" · ".join(parts)}</p>\n'


def inline_figures(body, docs_dir):
    """<p><img src="figures/x.svg" alt="..."></p> -> <figure> with the SVG itself inside."""
    def figure(m):
        tag = m.group(1)
        src = re.search(r'src="([^"]+)"', tag).group(1)
        alt = re.search(r'alt="([^"]*)"', tag)
        with open(os.path.join(docs_dir, src), encoding="utf-8") as f:
            svg = re.sub(r"<\?xml.*?\?>", "", f.read()).strip()
        svg = re.sub(r'\s(width|height)="\d+"', "", svg, count=2)     # let CSS size it; the viewBox keeps the shape
        label = f' aria-label="{alt.group(1)}"' if alt and alt.group(1) else ""
        return f'<figure role="img"{label}>\n{svg}\n</figure>'

    return re.sub(r'<p>(<img [^>]*src="figures/[^"]+\.svg"[^>]*>)</p>', figure, body)


def main(src, dst):
    name, lang = split_name(src)
    lang = lang or "en"
    ui = UI.get(lang, UI["en"])
    with open(src, encoding="utf-8") as f:
        text = f.read()
    title = re.search(r"^# (.+)$", text, re.M).group(1).strip()
    title = re.sub(r"\$([^$]+)\$", r"\1", title)

    text, formulas = protect_math(text)
    md = markdown.Markdown(
        extensions=["tables", "fenced_code", "codehilite", "md_in_html", "attr_list", "toc"],
        extension_configs={
            "codehilite": {"css_class": "code", "guess_lang": False},
            "toc": {"slugify": section_id, "toc_depth": "2-3", "permalink": "#", "permalink_class": "anchor",
                    "permalink_title": ui["anchor"]},
        })
    body = md.convert(text)
    # The page title needs neither an id nor a "#" link.
    body = re.sub(r'<h1 id="[^"]*">(.*?)<a class="anchor"[^>]*>#</a></h1>', r'<h1>\1</h1>', body, count=1, flags=re.S)
    toc = toc_list(md.toc_tokens)

    rendered = render_math(formulas) if formulas else []
    in_browser = rendered is None
    if in_browser:
        print("  note: KaTeX not found; formulas will be rendered in the browser (see scripts/install-build-deps.sh)")
        rendered = [html.escape(f, quote=False) for f in formulas]

    def restore(fragment):
        return re.sub(r"MATHPLACEHOLDER(\d+)X", lambda m: rendered[int(m.group(1))], fragment)

    body, toc = restore(body), restore(toc)

    body = inline_figures(body, os.path.dirname(src))
    body = body.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    # Links to other articles are written to the Markdown files; on the site they go to the pages.
    body = re.sub(r'href="([\w.-]+)\.md(#[^"]*)?"', lambda m: f'href="{m.group(1)}.html{m.group(2) or ""}"', body)
    # External links open in a new tab; links within this site (relative, or to krm-demo.org) stay in the same one.
    def external(m):
        tag = m.group(0)
        href = re.search(r'href="([^"]+)"', tag).group(1)
        if "target=" in tag or not re.match(r"https?://", href) or re.match(r"https?://(www\.)?krm-demo\.org(/|$)", href):
            return tag
        return tag[:-1] + ' target="_blank" rel="noopener">'
    body = re.sub(r"<a\s[^>]*>", external, body)

    # First paragraph, without markup, as the page description.
    first = re.search(r"<p>(.*?)</p>", body, re.S)
    plain = re.sub(r"<[^>]+>", "", first.group(1)) if first else ""
    plain = re.sub(r"\s+", " ", html.unescape(plain)).strip()
    description = html.escape(plain[:200].rsplit(" ", 1)[0] if len(plain) > 200 else plain, quote=True)

    # Translations: docs/<name>.<lang>.md next to this one -> language switcher + <link rel="alternate">
    langs = sorted(split_name(p)[1] for p in glob.glob(os.path.join(os.path.dirname(src), name + ".??.md")))
    switcher, alternates = "", ""
    if len(langs) > 1:
        items = []
        for code in langs:
            label, full = code.upper(), LANG_NAMES.get(code, code)
            if code == lang:
                items.append(f'<span class="lang-badge active" lang="{code}" title="{full}">{label}</span>')
            else:
                items.append(f'<a class="lang-badge" href="{name}.{code}.html" hreflang="{code}" lang="{code}" '
                             f'title="{full}">{label}</a>')
            alternates += f'    <link rel="alternate" hreflang="{code}" href="{name}.{code}.html">\n'
        switcher = f'<span class="lang-switch">· {ui["versions"]} {"".join(items)}</span>'

    toc_html = ""
    if toc:
        # Narrow screens show this collapsed copy, placed after the title and its note; wide screens show the side column.
        inline = f'<details class="toc-inline"><summary>{ui["contents"]}</summary>{toc}</details>'
        body = re.sub(r'(<h1>.*?</h1>\s*<p>.*?</p>)', lambda m: m.group(1) + '\n' + inline, body, count=1, flags=re.S)
        toc_html = (f'    <nav class="toc" aria-label="{ui["contents"]}">\n'
                    f'        <details open><summary>{ui["contents"]}</summary>{toc}</details>\n    </nav>\n')

    math_head = "" if not formulas else (MATH_HEAD_BROWSER if in_browser else MATH_HEAD_STATIC)
    page = TEMPLATE.format(
        lang=lang, title=html.escape(title), description=description, source=src.replace(os.sep, "/"),
        repo=REPO_URL, body=body, toc=toc_html, layout_class="" if toc else " no-toc",
        section=ui["section"], home=ui["home"], source_label=ui["source"],
        switcher=switcher, alternates=alternates, math_head=math_head, dates=dates_line(name, lang))
    with open(dst, "w", encoding="utf-8") as f:
        f.write(page)
    how = "" if not formulas else (" (math: in the browser)" if in_browser else f" ({len(formulas)} formulas)")
    print(f"wrote {dst} from {src}{how}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
