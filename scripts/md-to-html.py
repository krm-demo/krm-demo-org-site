#!/usr/bin/env python3
"""Turns a Markdown article from docs/ into a page of the site, in the site's Bootstrap layout.

    usage: scripts/md-to-html.py docs/<name>[.<lang>].md site/<name>[.<lang>].html

- Language: taken from the file name (chebyshev.ru.md -> "ru"); without a suffix the article is English.
  Translations are the other docs/<name>.<lang>.md files; each page gets a language switcher for them.
- Math: $...$ (inline) and $$...$$ (display) are passed through untouched and rendered by KaTeX in the browser.
  The same syntax renders on GitHub, so the Markdown source stays readable there.
- Raw HTML blocks with markdown="1" (e.g. <details markdown="1"> for collapsible proofs) get their
  inside rendered as Markdown.

The Markdown file is the source; the HTML file is generated and committed (the build doesn't run this).
After editing the Markdown, run this again and commit both files.
Needs Python 3 with the "markdown" package (pip install markdown).
"""
import glob
import html
import os
import re
import sys

import markdown

REPO_URL = "https://github.com/krm-demo/krm-demo-org-site"

LANG_NAMES = {"en": "English", "ru": "Русский"}
UI = {
    "en": {"home": "Home", "source": "Markdown source", "section": "Pulp Fiction", "versions": "Read in"},
    "ru": {"home": "Главная", "source": "Исходник в Markdown", "section": "Pulp Fiction", "versions": "Читать на"},
}

TEMPLATE = """<!DOCTYPE html>
<html lang="{lang}">
<head>
    <title>{title} — krm-demo</title>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
{alternates}    <link href="https://cdn.jsdelivr.net/npm/bootstrap@5.3.2/dist/css/bootstrap.min.css" rel="stylesheet">
    <script src="https://cdn.jsdelivr.net/npm/bootstrap@5.3.2/dist/js/bootstrap.bundle.min.js"></script>
{math_head}    <link href="site.css" rel="stylesheet">
</head>
<body>
<!-- Generated by scripts/md-to-html.py from {source} — edit the Markdown, not this file. -->

<!-- Header -->
<div class="container-fluid p-1 bg-primary text-white text-center">
    <h1><a href="./" class="text-white text-decoration-none">krm-demo</a></h1>
    <p>{section}</p>
</div>

<!-- Body (Content) -->
<div class="container mt-4 mb-5 pb-5">
    <nav class="article-nav small">
        <a href="./">&larr; {home}</a> · <a href="{repo}/blob/main/{source}" target="_blank" rel="noopener">{source_label}</a>
        {switcher}
    </nav>
    <article>
{body}
    </article>
</div>

<!-- Footer -->
<footer class="p-1 text-center fixed-bottom ">
    <div class="text-center p-1 site-footer-bar">
        <small class="text-secondary"><span id="build-info">loading build info…</span></small>
    </div>
</footer>
<script src="build-site-info.js"></script>

</body>
</html>
"""

# KaTeX renders $...$ and $$...$$ after the page loads; it is only included when the article has math.
MATH_HEAD = """    <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.css">
    <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.js"></script>
    <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/contrib/auto-render.min.js"
            onload="renderMathInElement(document.querySelector('article'), {delimiters: [
                {left: '$$', right: '$$', display: true}, {left: '$', right: '$', display: false}],
                throwOnError: false});"></script>
"""

# $$...$$ first (may span lines), then $...$ on one line; "\\$" is a literal dollar sign.
MATH_RE = re.compile(r"\$\$.+?\$\$|(?<![\\$])\$(?![\s$])[^$\n]+?(?<!\s)\$", re.S)
CODE_RE = re.compile(r"```.*?```|`[^`\n]+`", re.S)


def split_name(path):
    """docs/chebyshev.ru.md -> ("chebyshev", "ru"); docs/page-refresh.md -> ("page-refresh", None)"""
    base = os.path.basename(path)[:-len(".md")]
    m = re.match(r"^(.*)\.([a-z]{2})$", base)
    return (m.group(1), m.group(2)) if m else (base, None)


def protect_math(text):
    """Swaps math for placeholders so Markdown leaves it alone; returns (text, restore, has_math)."""
    saved, codes = [], []

    def keep(m):
        saved.append(m.group(0))
        return f"MATHPLACEHOLDER{len(saved) - 1}X"

    def keep_code(m):
        codes.append(m.group(0))
        return f"CODEPLACEHOLDER{len(codes) - 1}X"

    # code may contain "$" that is not math: hide code first, then the math, then bring the code back
    text = CODE_RE.sub(keep_code, text)
    text = MATH_RE.sub(keep, text)
    text = re.sub(r"CODEPLACEHOLDER(\d+)X", lambda m: codes[int(m.group(1))], text)

    def restore(rendered):
        return re.sub(r"MATHPLACEHOLDER(\d+)X", lambda m: html.escape(saved[int(m.group(1))], quote=False), rendered)

    return text, restore, bool(saved)


def main(src, dst):
    name, lang = split_name(src)
    lang = lang or "en"
    ui = UI.get(lang, UI["en"])
    text = open(src, encoding="utf-8").read()
    title = re.search(r"^# (.+)$", text, re.M).group(1).strip()
    title = re.sub(r"\$([^$]+)\$", r"\1", title)

    text, restore, has_math = protect_math(text)
    body = markdown.markdown(text, extensions=["tables", "fenced_code", "md_in_html", "attr_list"])
    body = restore(body)
    # Bootstrap styling; wide tables scroll sideways on narrow screens instead of squeezing.
    body = body.replace("<table>", '<div class="table-responsive"><table class="table table-sm table-bordered align-top">')
    body = body.replace("</table>", "</table></div>")
    body = body.replace("<thead>", '<thead class="table-light">')
    # External links open in a new tab; links inside the site stay relative.
    body = re.sub(r'<a href="(https?://[^"]+)">', r'<a href="\1" target="_blank" rel="noopener">', body)

    # Translations: docs/<name>.<lang>.md next to this one -> language switcher + <link rel="alternate">
    langs = sorted(split_name(p)[1] for p in glob.glob(os.path.join(os.path.dirname(src), name + ".??.md")))
    switcher, alternates = "", ""
    if len(langs) > 1:
        items = []
        for code in langs:
            label, full = code.upper(), LANG_NAMES.get(code, code)
            if code == lang:
                items.append(f'<span class="lang-badge active" lang="{code}" title="{full}">{label}</span>')
            else:
                items.append(f'<a class="lang-badge" href="{name}.{code}.html" hreflang="{code}" lang="{code}" '
                             f'title="{full}">{label}</a>')
            alternates += f'    <link rel="alternate" hreflang="{code}" href="{name}.{code}.html">\n'
        switcher = f'<span class="lang-switch ms-2">· {ui["versions"]} {" ".join(items)}</span>'

    page = TEMPLATE.format(
        lang=lang, title=html.escape(title), source=src, repo=REPO_URL, body=body,
        section=ui["section"], home=ui["home"], source_label=ui["source"],
        switcher=switcher, alternates=alternates, math_head=MATH_HEAD if has_math else "")
    open(dst, "w", encoding="utf-8").write(page)
    print(f"wrote {dst} from {src}" + (" (with math)" if has_math else ""))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
